import * as React from "react"
import { cn } from "cn"

function Card({
  className,
  size = "default",
  ...props
}: React.ComponentProps<"div"> & { size?: "default" | "sm" }) {
  return (
    <div
      data-slot="card"
      data-size={size}
      className={cn(
        "group/card flex flex-col gap-(--card-gap) overflow-hidden rounded-[24px] surface-gradient py-(--card-spacing) text-[15px] text-card-foreground has-data-[slot=card-footer]:pb-0 has-[>img:first-child]:pt-0 data-[size=default]:[--card-gap:--spacing(5)] data-[size=default]:[--card-spacing:--spacing(6)] data-[size=default]:sm:[--card-spacing:--spacing(8)] data-[size=sm]:[--card-gap:--spacing(3)] data-[size=sm]:[--card-spacing:--spacing(5)] data-[size=sm]:sm:[--card-spacing:--spacing(6)]",
        className
      )}
      {...props}
    />
  )
}

